export function getPageCopy(language: PageLanguage): PageCopy {
  return language === "pt-BR" ? portuguese : english
}
export function applyPageCopy(language: PageLanguage) {
  const copy = getPageCopy(language)
  document.documentElement.lang = language
  for (const node of document.querySelectorAll<HTMLElement>("[data-copy]")) {
    const key = node.dataset.copy
    if (key && key in copy) node.textContent = copy[key as PageCopyKey]
  }
  for (const node of document.querySelectorAll<HTMLElement>("[data-copy-aria]")) {
    const key = node.dataset.copyAria
    if (key && key in copy) node.setAttribute("aria-label", copy[key as PageCopyKey])
  }
  return copy
}
